import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

const projectRoot = process.cwd();
const sources = [
  {
    file: "client/src/data/locationData.ts",
    exportName: "locationLastModified",
    comment: "Service-area content timestamps, derived from the latest git-blamed line in each current location record.",
    allowedKeysFile: "client/src/data/locationSlugIndex.ts",
  },
  {
    file: "client/src/data/countyData.ts",
    exportName: "countyLastModified",
    comment: "County-hub content timestamps, derived from the latest git-blamed line in each current county record.",
  },
];

function getBlameDates(file) {
  const output = execFileSync("git", ["blame", "--line-porcelain", "--", file], {
    cwd: projectRoot,
    encoding: "utf8",
    maxBuffer: 32 * 1024 * 1024,
  });

  const datesByLine = new Map();
  const records = output.split("\n");
  let line = 0;
  let authorTime = 0;
  for (const record of records) {
    const header = record.match(/^[0-9a-f^]{40}\s+\d+\s+(\d+)(?:\s+\d+)?$/);
    if (header) {
      line = Number(header[1]);
      authorTime = 0;
    } else if (record.startsWith("author-time ")) {
      authorTime = Number(record.slice("author-time ".length));
    } else if (record.startsWith("\t") && line > 0) {
      datesByLine.set(line, authorTime ? new Date(authorTime * 1000).toISOString().slice(0, 10) : null);
      line += 1;
    }
  }
  return datesByLine;
}

function loadAllowedKeys(file) {
  if (!file) return null;
  return new Set(
    [...readFileSync(join(projectRoot, file), "utf8").matchAll(/^\s{2}"([^"]+)":/gm)].map((match) => match[1]),
  );
}

function buildRecordDates(file, allowedKeys) {
  const sourceLines = readFileSync(join(projectRoot, file), "utf8").split("\n");
  const blameDates = getBlameDates(file);
  const timestamps = {};

  for (let index = 0; index < sourceLines.length; index += 1) {
    const keyMatch = sourceLines[index].match(/^\s{2}"([^"]+)":\s*\{$/);
    if (!keyMatch) continue;

    const slug = keyMatch[1];
    if (allowedKeys && !allowedKeys.has(slug)) continue;
    let depth = 0;
    let lastModified = "";
    for (let cursor = index; cursor < sourceLines.length; cursor += 1) {
      const current = sourceLines[cursor];
      depth += (current.match(/\{/g) || []).length;
      depth -= (current.match(/\}/g) || []).length;
      const date = blameDates.get(cursor + 1);
      if (date && date > lastModified) lastModified = date;
      if (depth === 0) {
        index = cursor;
        break;
      }
    }
    if (lastModified) timestamps[slug] = lastModified;
  }
  return timestamps;
}

const outputLines = [
  "/**",
  " * Generated by scripts/generate-sitemap-lastmod.mjs.",
  " * Re-run this script whenever location or county content changes.",
  " */",
  "",
];

for (const source of sources) {
  const records = buildRecordDates(source.file, loadAllowedKeys(source.allowedKeysFile));
  outputLines.push(`// ${source.comment}`);
  outputLines.push(`export const ${source.exportName}: Record<string, string> = {`);
  for (const [slug, date] of Object.entries(records).sort(([a], [b]) => a.localeCompare(b))) {
    outputLines.push(`  ${JSON.stringify(slug)}: ${JSON.stringify(date)},`);
  }
  outputLines.push("};", "");
}

const target = join(projectRoot, "shared/sitemapLastModified.ts");
mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, `${outputLines.join("\n")}\n`);
console.log(`Generated ${target}`);
